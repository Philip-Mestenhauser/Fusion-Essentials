def is_write_tool(item):
    """True when a registered Item DECLARES itself a write - ``annotations.read_only is False``.

    A missing annotation and ``read_only is None`` both answer False: a tool that never declared its
    write status is not a write tool for a lint's purposes, and test_write_status_annotations is the
    gate that no such tool exists."""
    ann = item.primitive.annotations
    return ann is not None and ann.read_only is False


def load_mcp_server():
    """Import the REAL server/mcp_server.py (plus task_manager) for wire-level tests.

    mcp_server.py lives four packages deep in the add-in (``<addin>.commands.mcpServer.server``)
    and imports ``....lib.fusion360utils`` relatively, so it cannot be imported through the flat
    ``mcpServer`` package load_tool uses. This builds a synthetic package chain, stubs futil
    (the server only calls log/handle_error), and aliases the ALREADY-LOADED canonical
    ``mcpServer.mcp_primitives`` modules into the chain - the SAME module objects, so
    ``isinstance(item, Item)`` checks inside the server hold for Items built by tool modules.
    Idempotent: returns the cached module on repeat calls. Loads under ``_no_bytecode()``, like
    load_tool - the server modules are spec-loaded repo source too.
    """
    full_name = f"{_SERVER_PKG_ROOT}.commands.mcpServer.server.mcp_server"
    if full_name in sys.modules:
        return sys.modules[full_name]

    with _no_bytecode():
        install_mock_adsk()
        if COMMANDS_DIR not in sys.path:
            sys.path.insert(0, COMMANDS_DIR)
        importlib.import_module("mcpServer.mcp_primitives")

        def _pkg(name):
            mod = types.ModuleType(name)
            mod.__path__ = []
            sys.modules[name] = mod
            return mod

        _pkg(_SERVER_PKG_ROOT)
        lib_pkg = _pkg(f"{_SERVER_PKG_ROOT}.lib")
        futil_stub = types.ModuleType(f"{_SERVER_PKG_ROOT}.lib.fusion360utils")
        futil_stub.log = lambda *a, **k: None
        futil_stub.handle_error = lambda *a, **k: None
        lib_pkg.fusion360utils = futil_stub
        sys.modules[futil_stub.__name__] = futil_stub
        _pkg(f"{_SERVER_PKG_ROOT}.commands")
        _pkg(f"{_SERVER_PKG_ROOT}.commands.mcpServer")
        _pkg(f"{_SERVER_PKG_ROOT}.commands.mcpServer.server")

        for suffix in ("", ".item", ".tool", ".annotations", ".registry"):
            src = "mcpServer.mcp_primitives" + suffix
            importlib.import_module(src)
            sys.modules[f"{_SERVER_PKG_ROOT}.commands.mcpServer.mcp_primitives{suffix}"] = \
                sys.modules[src]
        importlib.import_module("mcpServer.version")
        sys.modules[f"{_SERVER_PKG_ROOT}.commands.mcpServer.version"] = sys.modules["mcpServer.version"]

        server_dir = os.path.join(COMMANDS_DIR, "mcpServer", "server")
        for mod_name in ("task_manager", "mcp_server"):
            fq = f"{_SERVER_PKG_ROOT}.commands.mcpServer.server.{mod_name}"
            spec = importlib.util.spec_from_file_location(
                fq, os.path.join(server_dir, f"{mod_name}.py"))
            module = importlib.util.module_from_spec(spec)
            sys.modules[fq] = module
            spec.loader.exec_module(module)
    return sys.modules[full_name]


# Pristine seam per tool module, captured ONCE the first time the module is seen — before any test
# patches it — so the autouse fixture can restore to it.
#
# A tool module reads the active design through one of a few module-level "seam" names: `app`
# (read by _common.design()), the imported-by-value `design`/`target_component`/`_design` helpers it
# calls bare, or `_data` (data tools). A test patches these on its OWN module object (e.g.
# `fl.target_component = lambda x: comp`, `mo.app = ...`). Because load_tool returns ONE canonical
# module object per tool for the whole session, such a patch LEAKS into the next test that uses the
# same module unless restored — producing order-dependent failures (the handler builds onto a stale
# fake). So the fixture restores these seam attrs on EVERY loaded tool module after each test, not
# just the substrate few. (`_design` covers the tools that bind a local `_design`.)
_PRISTINE_SEAMS = {}
_SEAM_ATTRS = ("design", "target_component", "_design", "app", "_data")


def _loaded_tool_modules():
    """Every currently-loaded `mcpServer.tools.*` module object (substrate + tools)."""
    return {name: mod for name, mod in sys.modules.items()
            if name.startswith("mcpServer.tools.") and mod is not None}


def _pristine_seam(key, mod):
    if key not in _PRISTINE_SEAMS:
        _PRISTINE_SEAMS[key] = {a: getattr(mod, a) for a in _SEAM_ATTRS if hasattr(mod, a)}
    return _PRISTINE_SEAMS[key]


def _capture_pristine_seams():
    """Record the as-imported seam values of every loaded tool module that has none recorded yet.

    Called from load_tool the moment a module is executed, and again at each test's SETUP. The
    load-time call is what makes the recording pristine: a module first imported inside a test BODY
    is already past that setup sweep, so without it the module's first recording happens at
    TEARDOWN - and a body that patched a seam imperatively (``mod.app = fake``) has the PATCHED
    value recorded as pristine and restored into the module for every test that follows."""
    for name, mod in _loaded_tool_modules().items():
        _pristine_seam(name, mod)


# Install mocks at collection time, before any test module imports a tool.
install_mock_adsk()


# Pristine snapshot of each adsk mock module's attribute namespace, captured ONCE right after install
# (before any test patches it). Tests routinely assign fake TYPE CLASSES and enum values onto these
# shared mocks — e.g. `adsk.fusion.BRepBody = SomeClass`, `adsk.fusion.MeshBody = ...`,
# `adsk.fusion.DesignTypes.ParametricDesignType = 1`, `adsk.core.Point3D.create = ...`. Because the
# mock modules are shared for the whole session, those assignments LEAK into later tests unless undone
# (a later test then isinstance-checks against the wrong class, or reads a stale enum, and fails only
# in certain orderings). Restoring each module's __dict__ to this snapshot after every test removes
# test-added attributes and reverts changed ones, making the suite order-independent.
def _snapshot_adsk_dicts():
    snap = {}
    for name in ("adsk.core", "adsk.fusion", "adsk.cam"):
        mod = sys.modules[name]
        # Shallow copy of the module-mock's own attribute dict, plus a shallow copy of each child
        # Mock's __dict__ one level down (that's where Type.cast / Type.create / Enum.MEMBER live).
        children = {}
        for attr, child in list(vars(mod).items()):
            cd = getattr(child, "__dict__", None)
            if isinstance(cd, dict):
                children[attr] = dict(cd)
        snap[name] = (dict(vars(mod)), children)
    return snap


def _restore_adsk_dicts(snap):
    for name, (top, children) in snap.items():
        mod = sys.modules[name]
        md = vars(mod)
        md.clear()
        md.update(top)
        for attr, cd in children.items():
            child = md.get(attr)
            chd = getattr(child, "__dict__", None)
            if isinstance(chd, dict):
                chd.clear()
                chd.update(cd)


_PRISTINE_ADSK = _snapshot_adsk_dicts()


@pytest.fixture(autouse=True)
def _restore_shared_adsk_mocks():
    """Snapshot-and-restore the mutable ``adsk`` mock attributes around every test.

    Tool tests install per-test behaviour by REASSIGNING attributes on the shared
    mocks — a cast/create callable (``adsk.fusion.Design.cast``,
    ``adsk.core.ValueInput.createByReal``), a fake type class
    (``adsk.fusion.BRepBody``), an enum member (``DesignTypes.*``). Because these
    live on module-level Mocks shared by the whole session, a reassignment would
    otherwise LEAK into later tests (e.g. a clobbered ``Design.cast`` pass-through
    makes an unrelated tool see no design at all). This autouse fixture records
    the originals before each test and puts them back after, keeping tests
    order-independent without per-file teardown.
    """
    # The whole adsk.core/fusion/cam mock namespace is snapshot/restored from _PRISTINE_ADSK (captured
    # once at install): test-assigned attributes are removed, reassigned ones reverted.
    # Tools that share _common.design()/target_component()/app (instead of a local _design()) are
    # tested by patching those on the _common module (the seam _inputs.py uses). Snapshot them at SETUP
    # and restore after, so a test's patch can't leak into a later test. _common is loaded lazily by
    # load_tool, so it may not exist yet on the very first tests — guard for that.
    # Capture pristine substrate seams at SETUP (before the test body patches them) - the backstop
    # under load_tool's own load-time capture, for a module that reached sys.modules another way.
    _capture_pristine_seams()
    # A few tests stub a tool's filesystem check by assigning `mod.os.path.isfile = lambda …`. Because
    # `mod.os` is the REAL os module, that mutates process-wide os.path and would leak into a later test
    # (e.g. a left-behind `isfile -> False` makes an unrelated upload report "file not found"). Snapshot
    # the real os.path predicates and restore them after the test.
    import os.path as _ospath
    _os_saved = [(_ospath, a, getattr(_ospath, a)) for a in ("isfile", "isdir", "exists")
                 if hasattr(_ospath, a)]
    # The registry SINGLETON is process-global, and several suite-wide tests populate it (a naming
    # lint's per-module reset+register loop, the wire-shape tests' full registration). Since
    # workspace_orient's pointer filter reads the live registry at call time, a leaked PARTIAL
    # registry makes pointer tests order-dependent. Snapshot the singleton pointer AND the instance's
    # tool dict at setup; restore both after - mirroring gen_manifest.collect()'s own guard.
    _reg_mod = sys.modules.get("mcpServer.mcp_primitives.registry")
    _reg_inst = _reg_mod._registry_instance if _reg_mod else None
    _reg_tools = dict(_reg_inst._tools) if _reg_inst is not None else None
    try:
        yield
    finally:
        if _reg_mod is not None:
            _reg_mod._registry_instance = _reg_inst
            if _reg_inst is not None:
                _reg_inst._tools.clear()
                _reg_inst._tools.update(_reg_tools)
        for _obj, _attr, _orig in _os_saved:
            setattr(_obj, _attr, _orig)
        _restore_adsk_dicts(_PRISTINE_ADSK)
        # load_tool returns ONE canonical object per tool module for the whole session, so a test that
        # patches a module-level seam (app/design/target_component/_design/_data) leaks into the next
        # test using that same module. Restore every loaded tool module's seam attrs to PRISTINE
        # (captured the first time the module is seen, before any patch — a per-test snapshot would
        # chain a prior test's patch forward and lose the original). This keeps the suite
        # order-independent without per-file teardown.
        for _name, _mod in _loaded_tool_modules().items():
            for attr, val in _pristine_seam(_name, _mod).items():
                setattr(_mod, attr, val)


# ── provenance declarations on the shared fakes ────────────────────────────

def fusion_fake(live_type=None, facts=(), factory_for=None, scenario_double=None):
    """Declare what a shared fake stands for and which measured rows back it.

    METADATA ONLY: this records ``__fusion_fake__`` and hands the object back untouched, so no
    fake's behaviour depends on being declared.

    ``live_type`` is the adsk type the fake impersonates, named by its SHAPES key - the same key
    test_fake_shapes_exist.py sweeps the fake's public members against - and ``facts`` are the
    measure_api row ids that measured what the fake encodes. A def that CONSTRUCTS a declared fake
    names it with ``factory_for``, so no builder of declared fakes sits outside the inventory.
    ``scenario_double`` classifies a double that impersonates no live type at all, its string being
    the reason.

    test_fake_shapes_exist.py resolves every id against measure_api.ROWS, so a row renamed or
    dropped from the registry turns each fake citing it red.
    """
    declaration = {"live_type": live_type, "facts": tuple(facts), "factory_for": factory_for,
                   "scenario_double": scenario_double}

    def declare(obj):
        obj.__fusion_fake__ = declaration
        return obj
    return declare


# ── small Fusion-shaped fakes a tool's logic branches on ───────────────────
